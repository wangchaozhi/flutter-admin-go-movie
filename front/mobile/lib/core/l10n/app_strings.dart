import 'package:flutter/widgets.dart';

import 'locale_controller.dart';

/// Lightweight i18n: flat dotted keys resolved per-locale with graceful
/// fallback to zh and then the key itself, plus {name} interpolation. Mirrors
/// the admin web app's approach so the two stay conceptually in sync.
class AppStrings {
  const AppStrings(this.locale);

  final Locale locale;

  Map<String, String> get _map => _all[AppLocale.codeOf(locale)] ?? _all['zh']!;

  String t(String key, [Map<String, String>? vars]) {
    var value = _map[key] ?? _all['zh']![key] ?? key;
    if (vars != null) {
      vars.forEach((name, replacement) {
        value = value.replaceAll('{$name}', replacement);
      });
    }
    return value;
  }

  static AppStrings of(BuildContext context) =>
      Localizations.of<AppStrings>(context, AppStrings) ??
      const AppStrings(Locale('zh'));

  static const LocalizationsDelegate<AppStrings> delegate =
      _AppStringsDelegate();
}

class _AppStringsDelegate extends LocalizationsDelegate<AppStrings> {
  const _AppStringsDelegate();

  @override
  bool isSupported(Locale locale) => AppLocale.values.any(
    (item) => item.locale.languageCode == locale.languageCode,
  );

  @override
  Future<AppStrings> load(Locale locale) async => AppStrings(locale);

  @override
  bool shouldReload(_AppStringsDelegate old) => false;
}

