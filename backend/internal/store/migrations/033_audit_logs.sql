-- Audit trail for admin mutations (POST/PUT/DELETE under /api/admin). Records who
-- did what, against which resource, and the resulting status, so destructive
-- actions (deletes, refunds, permission changes) leave a reviewable trace.
CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id TEXT NOT NULL DEFAULT '',
  username   TEXT NOT NULL DEFAULT '',
  method     TEXT NOT NULL DEFAULT '',
  path       TEXT NOT NULL DEFAULT '',
  status     INT  NOT NULL DEFAULT 0,
  ip         TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at ON audit_logs(id DESC);
CREATE INDEX IF NOT EXISTS idx_audit_logs_username ON audit_logs(username);

