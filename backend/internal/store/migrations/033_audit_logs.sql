  (37, '审计日志', '/audit-logs', 0, 'menu', '', 'ScrollText', 26)
ON CONFLICT (id) DO UPDATE SET
  name       = EXCLUDED.name,
  path       = EXCLUDED.path,
  parent_id  = EXCLUDED.parent_id,
  type       = EXCLUDED.type,
  permission = EXCLUDED.permission,
  icon       = EXCLUDED.icon,
  sort_order = EXCLUDED.sort_order;

UPDATE admin_roles
SET menu_ids = menu_ids || '[37]'::jsonb
WHERE role_key = 'super_admin'
  AND NOT menu_ids @> '[37]'::jsonb;

